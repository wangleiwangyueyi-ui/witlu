import { lazy, StrictMode, Suspense } from 'react';
import { createRoot } from 'react-dom/client';
import './styles/app.css';
import './styles/timeline.css';
import './styles/chapters.css';
import './styles/weather.css';
import './styles/places.css';
import './styles/explore.css';
import { App } from './App';
const ExploreLab=lazy(()=>import('./lab/ExploreLab'));
const PlacesLab = lazy(() => import('./lab/PlacesLab'));
const WeatherLab = lazy(() => import('./lab/WeatherLab'));
const ChaptersLab = lazy(() => import('./lab/ChaptersLab'));
const TimeFlightLab = lazy(() => import('./lab/TimeFlightLab'));
const TimelineLab = lazy(() => import('./lab/TimelineLab'));
const GlassLab = lazy(() => import('./lab/GlassLab'));
const TerrainLab = lazy(() => import('./lab/TerrainLab'));
const EnvironmentLab = lazy(() => import('./lab/EnvironmentLab'));
const MorphLab = lazy(() => import('./lab/MorphLab'));
createRoot(document.getElementById('root')!).render(<StrictMode><Suspense fallback={null}>{location.pathname === '/lab/explore' ? <ExploreLab/> : location.pathname === '/lab/places' ? <PlacesLab/> : location.pathname === '/lab/weather' ? <WeatherLab/> : location.pathname === '/lab/chapters' ? <ChaptersLab/> : location.pathname === '/lab/time-flight' ? <TimeFlightLab/> : location.pathname === '/lab/timeline' ? <TimelineLab/> : location.pathname === '/lab/glass' ? <GlassLab/> : location.pathname === '/lab/terrain' ? <TerrainLab/> : location.pathname === '/lab/ocean' ? <EnvironmentLab mode="ocean"/> : location.pathname === '/lab/clouds' ? <EnvironmentLab mode="clouds"/> : location.pathname === '/lab/morph' ? <MorphLab/> : <App/>}</Suspense></StrictMode>);
