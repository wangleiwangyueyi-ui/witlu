import type { EngineStats } from '../packages/engine/Renderer';
test('morph lab prepares GPU labels and renders reversible states', async ({ page }, info) => {
    test.setTimeout(90000);
    const errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', e => { if (e.type() === 'error')
        errors.push(e.text()); });
    await page.goto('/lab/morph');
    const stats = async () => JSON.parse((await page.getByTestId('terrain').getAttribute('data-stats'))!) as EngineStats;
    await expect(page.getByTestId('terrain')).toHaveAttribute('data-ready', 'true', { timeout: 30000 });
    await expect.poll(async () => (await stats()).morph.ready, { timeout: 45000 }).toBe(true);
    expect((await stats()).morph.error).toBeNull();
    expect((await stats()).morph.labelSize).toBe(info.project.name === 'desktop' ? 4096 : 2048);
    await fs.mkdir('docs/progress/screenshots/P4', { recursive: true });
    await page.screenshot({ path: `docs/progress/screenshots/P4/${info.project.name}-start.png` });
    await page.getByRole('button', { name: '正放', exact: true }).click();
    await expect.poll(async () => (await stats()).morph.t).toBe(1);
    await page.screenshot({ path: `docs/progress/screenshots/P4/${info.project.name}-end.png` });
    await page.getByRole('button', { name: '倒放', exact: true }).click();
    await expect.poll(async () => (await stats()).morph.t).toBe(0);
    expect(errors).toEqual([]);
});
test('morph lifecycle, caching, reduced motion and rapid drag fallback', async ({ page }, info) => {
    test.skip(info.project.name !== 'desktop', 'One worker/cache/context audit');
    test.setTimeout(90000);
    await page.goto('/lab/morph');
    await expect.poll(async () => JSON.parse((await page.getByTestId('terrain').getAttribute('data-stats')) ?? '{}').morph?.ready, { timeout: 45000 }).toBe(true);
    const proof = await page.evaluate(async () => {
        const { terrainBridge } = await import('/src/state/terrain.ts' as string), m = terrainBridge.engine!.morph;
        const frame = () => new Promise<void>(r => requestAnimationFrame(() => requestAnimationFrame(() => r())));
        m.setProgress(.2, 'seek');
        await frame();
        m.setProgress(.8, 'drag', 400);
        const immediate = m.stats();
        await new Promise(r => setTimeout(r, 180));
        const settled = m.stats();
        const pair = m.stats();
        await Promise.all([m.play(pair.snapshotA, pair.snapshotB),m.prepare(pair.snapshotA, pair.snapshotA)]);
        const superseded=m.stats();
        await m.prepare(pair.snapshotA, pair.snapshotB);
        const cached = m.stats();
        m.setProgress(.4, 'seek');
        await frame();
        const before = await m.audit();
        return { immediate, settled, cached, before, superseded };
    });
    expect(proof.immediate.mode).toBe('crossfade');
    expect(proof.immediate.playing).toBe(true);
    expect(proof.immediate.t).toBeCloseTo(.2, 2);
    expect(proof.settled.t).toBe(.8);
    expect(proof.settled.playing).toBe(false);
    expect(proof.cached.cacheHit).toBe(true);
    expect(proof.superseded.playing).toBe(false);
    expect(proof.superseded.snapshotA).toBe(proof.superseded.snapshotB);
    expect(proof.cached.cacheBytes).toBeLessThanOrEqual(96 * 1024 * 1024);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    const reduced = await page.evaluate(async () => { const { terrainBridge } = await import('/src/state/terrain.ts' as string); const m = terrainBridge.engine!.morph; m.playPrepared(false); await new Promise(r => setTimeout(r, 200)); return { ...m.stats(), front: m.uniforms.territoryFront!.value as number, ink: m.uniforms.territoryInk!.value as number, particles: m.uniforms.particleEnabled!.value as number }; });
    expect(reduced.mode).toBe('crossfade');
    expect(reduced.t).toBe(1);
    expect([reduced.front, reduced.ink, reduced.particles]).toEqual([0, 0, 0]);
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await page.evaluate(async () => { const { terrainBridge } = await import('/src/state/terrain.ts' as string); terrainBridge.engine!.morph.setProgress(.4, 'seek'); const ext = document.querySelector('canvas')!.getContext('webgl2')!.getExtension('WEBGL_lose_context')!; ext.loseContext(); setTimeout(() => ext.restoreContext(), 1200); });
    await expect(page.getByTestId('terrain')).toHaveAttribute('data-context', 'lost');
    await expect(page.getByTestId('terrain')).toHaveAttribute('data-context', 'ready', { timeout: 20000 });
    await expect.poll(async () => JSON.parse((await page.getByTestId('terrain').getAttribute('data-stats'))!).morph.ready, { timeout: 30000 }).toBe(true);
    const after = await page.evaluate(async () => { const { terrainBridge } = await import('/src/state/terrain.ts' as string); return terrainBridge.engine!.morph.audit(); });
    expect(after.hash).toBe(proof.before.hash);
    expect(after.gaps).toBe(0);
    const modern:EngineStats['morph']=await page.evaluate(async()=>{const {terrainBridge}=await import('/src/state/terrain.ts' as string);const m=terrainBridge.engine!.morph;await m.prepare('s_roc_d','s_prc');return m.stats();});
    expect(modern.seedSources.find(s=>s.polity==='unprofiled:prc:中华人民共和国')?.source).toBe('capital');
    await fs.mkdir('docs/progress/performance/P4', { recursive: true });
    await fs.writeFile('docs/progress/performance/P4/lifecycle.json', JSON.stringify({ proof, reduced, after, modern }, null, 2) + '\n');
});
